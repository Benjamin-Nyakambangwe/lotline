/**
 * M0 discovery: probe ABC Auctions' public API (read-only, throttled) and write
 *   - docs/abc-api.md            human-readable findings
 *   - tests/fixtures/abc/*.json  sample payloads with bidder IDs scrubbed
 *
 * usage: npx tsx scripts/discover-abc.ts
 *
 * Polite by design: one request at a time, at most 1 per second, generic User-Agent.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const API = "https://app-api.abcauctions.co.zw/lots";
const UA = "Mozilla/5.0";
const ROOT = join(import.meta.dirname, "..");
const FIXTURES = join(ROOT, "tests", "fixtures", "abc");
const DOCS = join(ROOT, "docs");

// ---------- polite fetch ----------
let lastAt = 0;
let requests = 0;
const timings: number[] = [];
let sampleHeaders: Record<string, string> = {};

async function get(path: string): Promise<unknown> {
  const wait = lastAt + 1000 - Date.now();
  if (wait > 0) await new Promise((r) => setTimeout(r, wait));
  lastAt = Date.now();
  requests++;
  const t0 = performance.now();
  const res = await fetch(`${API}/${path}`, { headers: { "User-Agent": UA } });
  timings.push(performance.now() - t0);
  if (requests === 1) sampleHeaders = Object.fromEntries(res.headers.entries());
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${path}`);
  return res.json();
}

type Json = Record<string, unknown>;
const unwrap = (d: unknown): Json => {
  const o = d as Json;
  return (
    o &&
    typeof o === "object" &&
    "Data" in o &&
    o.Data &&
    typeof o.Data === "object"
      ? o.Data
      : o
  ) as Json;
};

function searchPath(opts: {
  size?: number;
  sort?: number;
  query?: string;
  facets?: Record<string, string[]>;
  cursor?: string;
}) {
  const q = new URLSearchParams();
  q.set("Size", String(opts.size ?? 100));
  if (opts.sort !== undefined) q.set("Sort", String(opts.sort));
  if (opts.query) q.set("Query", opts.query);
  if (opts.facets) q.set("FacetJson", JSON.stringify(opts.facets));
  if (opts.cursor) q.set("Cursor", opts.cursor);
  return `search?${q.toString()}`;
}

interface Bucket {
  Value: string;
  Count: number;
}
interface Facet {
  Name: string;
  Title?: string;
  Buckets: Bucket[];
}
interface SearchResult {
  List: Json[];
  Meta: { Count: number; Cursor?: string | null; Facets?: Facet[] };
}

async function search(
  opts: Parameters<typeof searchPath>[0],
): Promise<SearchResult> {
  return unwrap(await get(searchPath(opts))) as unknown as SearchResult;
}
async function detail(id: number, type = 1): Promise<Json> {
  return unwrap(await get(`detail?id=${id}&type=${type}`));
}

// ---------- scrubbing: bidder IDs are personal data, never commit real ones ----------
const FAKE_BASE = 900_000_001;
const fakeIds = new Map<number, number>();
function scrub<T>(v: T): T {
  if (Array.isArray(v)) return v.map(scrub) as T;
  if (v && typeof v === "object") {
    const out: Json = {};
    for (const [k, val] of Object.entries(v as Json)) {
      if (k === "CurrentBidderId" && typeof val === "number") {
        if (!fakeIds.has(val)) fakeIds.set(val, FAKE_BASE + fakeIds.size);
        out[k] = fakeIds.get(val);
      } else if (k === "MaxBid" || k === "HighestBidder" || k === "Watching") {
        out[k] = k === "MaxBid" ? null : false;
      } else out[k] = scrub(val);
    }
    return out as T;
  }
  return v;
}
function saveFixture(name: string, data: unknown) {
  writeFileSync(
    join(FIXTURES, name),
    `${JSON.stringify(scrub(data), null, 2)}\n`,
  );
}

// ---------- helpers ----------
const now = Date.now();
const ts = (s: unknown) => (typeof s === "string" ? Date.parse(s) : Number.NaN);
const isSorted = (xs: number[], dir: 1 | -1) =>
  xs.every((x, i) => i === 0 || (x - xs[i - 1]) * dir >= 0);
const md: string[] = [];
const h = (s: string) => md.push(`\n## ${s}\n`);
const p = (s: string) => md.push(s);

async function main() {
  mkdirSync(FIXTURES, { recursive: true });
  mkdirSync(DOCS, { recursive: true });
  const AV = { sale_status: ["Available"] };

  p(`# ABC Auctions public API — discovery notes\n`);
  p(
    `Generated by \`scripts/discover-abc.ts\` on ${new Date().toISOString()} (read-only, ≤1 req/s, UA \`${UA}\`).`,
  );
  p(
    `Hand-written notes and decisions live in the "Decisions" section at the end; re-running the script regenerates everything above it.`,
  );

  // 1. Sale statuses and facet caps
  h("Sale statuses and facets");
  const all = await search({ size: 1 });
  const ss = all.Meta.Facets?.find((f) => f.Name === "sale_status");
  p(
    `Unfiltered total: **${all.Meta.Count}** lots. sale_status buckets: ${ss?.Buckets.map((b) => `${b.Value} ${b.Count}`).join(" · ") ?? "–"}.`,
  );
  const avail = await search({ size: 1, facets: AV });
  p(`\n| Facet | Buckets (no filter) | Buckets (Available) |\n|---|---|---|`);
  for (const f of all.Meta.Facets ?? []) {
    const g = avail.Meta.Facets?.find((x) => x.Name === f.Name);
    p(`| ${f.Name} | ${f.Buckets.length} | ${g?.Buckets.length ?? "–"} |`);
  }
  p(
    `\nBuckets look capped at 10 per facet. Available campaigns: ${
      avail.Meta.Facets?.find((f) => f.Name === "campaign")
        ?.Buckets.map((b) => `${b.Value} (${b.Count})`)
        .join("; ") ?? "–"
    }.`,
  );
  saveFixture("search-available-meta.json", avail);

  // 2. Sort codes
  h("Sort codes");
  p(
    `| Sort | EndDate asc | EndDate desc | LotNumber asc | Id asc | First EndDate | First title |\n|---|---|---|---|---|---|---|`,
  );
  for (const s of [0, 1, 2, 3, 4, 5, 6]) {
    const r = await search({ size: 12, sort: s, facets: AV });
    const ends = r.List.map((x) => ts(x.EndDate));
    const lotnos = r.List.map((x) => Number(x.LotNumber));
    const ids = r.List.map((x) => Number(x.Id));
    const yn = (b: boolean) => (b ? "yes" : "no");
    p(
      `| ${s} | ${yn(isSorted(ends, 1))} | ${yn(isSorted(ends, -1))} | ${yn(isSorted(lotnos, 1))} | ${yn(isSorted(ids, 1))} | ${r.List[0]?.EndDate ?? "–"} | ${String(r.List[0]?.Title ?? "").slice(0, 40)} |`,
    );
  }
  p(
    `\nDecision: never rely on server sort order; sync with a stable sort and sort locally.`,
  );

  // 3. Page size and cursor stability
  h("Page size and cursors");
  for (const size of [100, 250, 500]) {
    const r = await search({ size, sort: 0, facets: AV });
    p(
      `- Size=${size} → ${r.List.length} items returned (Count ${r.Meta.Count}), cursor ${r.Meta.Cursor ? "present" : "absent"}.`,
    );
  }
  const a1 = await search({ size: 50, sort: 0, facets: AV });
  const a2 = await search({ size: 50, sort: 0, facets: AV });
  p(
    `- Same first page twice → cursors ${a1.Meta.Cursor === a2.Meta.Cursor ? "identical" : "different"}; first ids ${a1.List[0]?.Id === a2.List[0]?.Id ? "identical" : "different"}.`,
  );
  if (a1.Meta.Cursor) {
    const b1 = await search({
      size: 50,
      sort: 0,
      facets: AV,
      cursor: a1.Meta.Cursor,
    });
    const b2 = await search({
      size: 50,
      sort: 0,
      facets: AV,
      cursor: a1.Meta.Cursor,
    });
    const overlap = b1.List.filter((x) =>
      a1.List.some((y) => y.Id === x.Id),
    ).length;
    p(
      `- Page 2 via cursor twice → ${b1.List.map((x) => x.Id).join(",") === b2.List.map((x) => x.Id).join(",") ? "identical" : "different"}; overlap with page 1: ${overlap}.`,
    );
    saveFixture("search-available-page2.json", b1);
  }
  saveFixture("search-available-page1.json", {
    ...a1,
    List: a1.List.slice(0, 12),
  });

  // 4. Text search
  h("Text search (Query)");
  const sample = a1.List.find((x) => x.LotNumber) ?? a1.List[0];
  const byLotNo = await search({
    size: 5,
    query: String(sample.LotNumber),
    facets: AV,
  });
  const byId = await search({ size: 5, query: String(sample.Id), facets: AV });
  const byWord = await search({ size: 5, query: "optiplex" });
  p(
    `- Query=<LotNumber ${sample.LotNumber}> → ${byLotNo.Meta.Count} hit(s); contains the lot: ${byLotNo.List.some((x) => x.Id === sample.Id)}.`,
  );
  p(
    `- Query=<Id ${sample.Id}> → ${byId.Meta.Count} hit(s); contains the lot: ${byId.List.some((x) => x.Id === sample.Id)}.`,
  );
  p(`- Query=optiplex (all statuses) → ${byWord.Meta.Count} hit(s).`);

  // 5. Ended-but-Available lots
  h("Lifecycle: ended lots, Sold placeholder dates");
  const early = await search({ size: 100, sort: 0, facets: AV });
  const ended = early.List.filter((x) => ts(x.EndDate) < now);
  const st = (xs: Json[]) =>
    Object.entries(
      xs.reduce<Record<string, number>>((acc, x) => {
        const k = `Status ${x.Status}/SaleStatus ${x.SaleStatus}`;
        acc[k] = (acc[k] ?? 0) + 1;
        return acc;
      }, {}),
    )
      .map(([k, v]) => `${k}: ${v}`)
      .join(", ");
  p(
    `- Of the first 100 Available lots (Sort=0), **${ended.length}** have EndDate in the past (${st(ended) || "–"}); with bids: ${ended.filter((x) => x.CurrentBid != null).length}.`,
  );
  const sold = await search({
    size: 100,
    sort: 0,
    facets: { sale_status: ["Sold"] },
  });
  const placeholder = sold.List.filter(
    (x) => new Date(String(x.EndDate)).getUTCFullYear() >= 2100,
  );
  p(
    `- Sold: ${sold.Meta.Count} lots; of the first 100, **${placeholder.length}** carry a placeholder EndDate (year ≥ 2100); statuses: ${st(sold.List)}; all have CurrentBid: ${sold.List.every((x) => x.CurrentBid != null)}.`,
  );
  saveFixture("search-sold-page1.json", {
    ...sold,
    List: sold.List.slice(0, 12),
  });
  const pending = await search({
    size: 20,
    facets: { sale_status: ["Pending"] },
  });
  p(
    `- Pending: ${pending.Meta.Count} lots; statuses: ${st(pending.List) || "–"}; first EndDate ${pending.List[0]?.EndDate ?? "–"}.`,
  );
  if (pending.List.length)
    saveFixture("search-pending-page1.json", {
      ...pending,
      List: pending.List.slice(0, 6),
    });

  // Watch a lot that closed on Fri 6 Nov to learn when the 2125 rewrite happens.
  const watched = await detail(795373);
  p(
    `- Lot 795373 (closed Fri 6 Nov): Status ${watched.Status}, SaleStatus ${watched.SaleStatus}, EndDate ${watched.EndDate}, CurrentBid ${watched.CurrentBid}. Re-run later to see when EndDate is rewritten.`,
  );
  saveFixture("detail-closed-795373.json", watched);

  // 6. Detail sampling across categories: fees, LotVAT, vehicle type
  h("Detail sampling: fees, LotVAT, types");
  const cats = (
    avail.Meta.Facets?.find((f) => f.Name === "category")?.Buckets ?? []
  )
    .slice(0, 8)
    .map((b) => b.Value);
  const seen: Json[] = [];
  for (const c of cats) {
    const r = await search({
      size: 3,
      sort: 0,
      facets: { sale_status: ["Available"], category: [c] },
    });
    for (const x of r.List.slice(0, 2)) {
      const d = await detail(Number(x.Id), Number(x.Type ?? 1));
      seen.push({ cat: c, ...d });
    }
  }
  const dist = (k: string) =>
    Object.entries(
      seen.reduce<Record<string, number>>((acc, d) => {
        const v = String(d[k]);
        acc[v] = (acc[v] ?? 0) + 1;
        return acc;
      }, {}),
    )
      .map(([v, n]) => `${v}×${n}`)
      .join(", ");
  p(`Sampled ${seen.length} details across ${cats.length} categories.`);
  p(`- PurchasersLevy: ${dist("PurchasersLevy")}`);
  p(`- VAT: ${dist("VAT")}`);
  p(`- LotVAT: ${dist("LotVAT")}`);
  p(
    `- Type: ${dist("Type")}; Condition: ${dist("Condition")}; State: ${dist("State")}`,
  );
  p(
    `- Detail keys: \`${Object.keys(seen[0] ?? {})
      .filter((k) => k !== "cat")
      .join("`, `")}\``,
  );
  const vatLot = seen.find((d) => Number(d.LotVAT) > 0);
  if (vatLot) {
    p(
      `- LotVAT > 0 example: lot ${vatLot.Id} (${vatLot.cat}) LotVAT=${vatLot.LotVAT}.`,
    );
    saveFixture("detail-lotvat.json", vatLot);
  } else p(`- No LotVAT > 0 in this sample. Keep the formula general.`);
  const open = seen.find((d) => d.Status === 1 && ts(d.EndDate) > now);
  if (open) saveFixture("detail-open.json", open);

  const veh = await search({
    size: 3,
    sort: 0,
    facets: { sale_status: ["Available"], lot_type: ["Vehicle"] },
  });
  const v0 = veh.List[0];
  if (v0) {
    p(`- Vehicle list item: Id ${v0.Id}, Type ${v0.Type}.`);
    let ok1 = "error";
    let okT = "error";
    try {
      const d1 = await detail(Number(v0.Id), 1);
      ok1 = d1?.Id ? `ok (Id ${d1.Id}, Url ${d1.Url})` : "empty";
    } catch (e) {
      ok1 = String(e);
    }
    try {
      const dT = await detail(Number(v0.Id), Number(v0.Type));
      okT = dT?.Id ? `ok (Url ${dT.Url})` : "empty";
      if (dT?.Id) saveFixture("detail-vehicle.json", dT);
    } catch (e) {
      okT = String(e);
    }
    p(`  - detail type=1 → ${ok1}`);
    p(`  - detail type=${v0.Type} → ${okT}`);
  }

  // 7. Transport
  h("Transport");
  const sorted = [...timings].sort((a, b) => a - b);
  const q = (f: number) =>
    Math.round(
      sorted[Math.min(sorted.length - 1, Math.floor(f * sorted.length))],
    );
  p(
    `- ${requests} requests; latency p50 ${q(0.5)} ms, p95 ${q(0.95)} ms (from this machine).`,
  );
  const keep = Object.entries(sampleHeaders).filter(([k]) =>
    /rate|limit|retry|cache|cf-|server|access-control|content-type/i.test(k),
  );
  p(
    `- Response headers of interest: ${keep.map(([k, v]) => `\`${k}: ${v}\``).join(", ") || "none"}.`,
  );
  p(
    `- No \`access-control-allow-origin\`: browsers can't call the API directly, so all calls are server-side.`,
  );
  p(
    `- Scrubbed ${fakeIds.size} distinct bidder IDs into the fake range ${FAKE_BASE}+.`,
  );

  h("Pending checks");
  p(
    `- Reachability and latency from a Railway region (run this script from a Railway shell before M6).`,
  );
  p(
    `- Search vs detail lag during a live close (compare both endpoints for a lot in its last 10 minutes).`,
  );
  p(
    `- When a closed lot's EndDate flips to the 2125 placeholder (re-run and compare lot 795373).`,
  );

  h("Decisions");
  p(
    `- Status codes seen: 0 = pending (not started), 1 = open, 2 = closed with a sale, 3 = ended with no bids (passed; still listed as "Available" during the offer window).`,
  );
  p(
    `- Open means \`Status == 1 && end_at > now\`; "Available" alone is not enough.`,
  );
  p(
    `- Page size up to 500 works: a full Available sync is ~5 requests. Use Size=500 for sync and sweeps.`,
  );
  p(
    `- \`Query\` matches ABC lot numbers (e.g. 261008571) but not lot Ids: use it to resolve a pasted lot number to an Id.`,
  );
  p(
    `- Vehicles are Type 2. Detail works with either type, but \`Url\` follows the type.`,
  );
  p(
    `- Cloudflare fronts the API (JNB edge from here): datacenter IPs may be challenged, so verify from Railway before relying on it.`,
  );
  p(
    `- Never derive close time from a Sold lot's EndDate; keep the last real EndDate we observed as \`closed_at\`, and ignore dates more than a year ahead.`,
  );
  p(`- Sort locally. Sync with Sort=0 and the cursor.`);
  p(
    `- Fees: \`allIn = hammer × (1 + LotVAT) + hammer × PurchasersLevy × (1 + VAT)\`, per lot.`,
  );
  p(
    `- Build lot links from the list item's Type: \`https://app.abcauctions.co.zw/home(dialog:lot/{Type}/{Id})\`.`,
  );

  writeFileSync(join(DOCS, "abc-api.md"), `${md.join("\n")}\n`);
  console.log(
    `done: ${requests} requests, ${fakeIds.size} bidder IDs scrubbed → docs/abc-api.md, tests/fixtures/abc/`,
  );
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
