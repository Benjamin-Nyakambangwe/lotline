CREATE TABLE "history_crawls" (
	"key" text PRIMARY KEY NOT NULL,
	"type" smallint NOT NULL,
	"start_id" integer NOT NULL,
	"next_id" integer NOT NULL,
	"cutoff" timestamp with time zone NOT NULL,
	"recent_ema" real DEFAULT 1 NOT NULL,
	"dated" integer DEFAULT 0 NOT NULL,
	"reached_at" timestamp with time zone,
	"missing_streak" integer DEFAULT 0 NOT NULL,
	"fetched" integer DEFAULT 0 NOT NULL,
	"sold" integer DEFAULT 0 NOT NULL,
	"passed" integer DEFAULT 0 NOT NULL,
	"other" integer DEFAULT 0 NOT NULL,
	"missing" integer DEFAULT 0 NOT NULL,
	"skipped" integer DEFAULT 0 NOT NULL,
	"errors" integer DEFAULT 0 NOT NULL,
	"day" date,
	"day_count" integer DEFAULT 0 NOT NULL,
	"started_at" timestamp with time zone DEFAULT now() NOT NULL,
	"updated_at" timestamp with time zone DEFAULT now() NOT NULL,
	"done_at" timestamp with time zone,
	"done_reason" text
);
